#!/usr/bin/env python3
"""Render commands for every animation in an episode — written, never run.

    render_plan.py <episode-dir> [--studio <hf-studio>] [--fps 60] [--resolution landscape-4k]

For each cutaway, transition and overlay in storyboard.json:
  composition   the slot's instance <episode>/<slot> when instances.py has made it (content baked
                in, no variables needed); otherwise reuse.from / reuse.as / the custom build
  variables     only without an instance: the slot's vars, plus duration / theme / placement /
                motion for kit components
  format        overlays → mov (ProRes 4444, alpha) · cutaways / transitions → mp4
  output        <episode>/renders/<slot>.<ext>   e.g. Seg_06.o1.mov, Seg_05.transition.mp4

Writes <episode>/renders.sh (the commands, for the user to run) and renders.md (what each
render is, and anything that blocks it: not built yet, no measured timing, fixed length).
"""

import argparse
import json
import os
import re
import shlex
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from storyboard import animations_of, find_studio, motion_entries, reuse_of, slot_dir  # noqa: E402
from ytlib import load_json  # noqa: E402

ROOT_DUR = re.compile(r"<[a-z]+\b[^>]*\bdata-composition-id=[^>]*>", re.S)


def fixed_length(comp_dir):
    try:
        html = (comp_dir / "index.html").read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return None
    root = ROOT_DUR.search(html)
    m = re.search(r'data-duration="([\d.]+)"', root.group(0)) if root else None
    return float(m.group(1)) if m else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("episode")
    ap.add_argument("--studio")
    ap.add_argument("--fps", type=int, default=60)
    ap.add_argument("--resolution", default="landscape-4k")
    args = ap.parse_args()

    ep = Path(args.episode).resolve()
    sb = load_json(ep / "storyboard.json")
    studio = find_studio(args.studio, ep)
    comps = studio / "compositions"
    theme = sb.get("theme", "channel")
    out_dir = ep / "renders"

    sh = ["#!/usr/bin/env bash", "# Generated by youtube-production render_plan.py — review, then run.",
          "set -euo pipefail", f"mkdir -p {shlex.quote(str(out_dir))}", ""]
    rows, blocked = [], 0
    for seg in sb["segments"]:
        seg_dur = (seg.get("timing") or {}).get("dur")
        for slot, layer, anim in animations_of(seg):
            r = reuse_of(anim)
            if r["mode"] in ("as-is", "variables"):
                comp = r["from"]
            else:
                comp = r["as"] or slot_dir(sb.get("episode", ep.name), slot)
            # An instance (instances.py) has this slot's content baked in: render it as-is.
            inst = slot_dir(sb.get("episode", ep.name), slot)
            from_instance = (comps / inst / "index.html").exists()
            if from_instance:
                comp = inst
            name = slot.replace(" (transition)", ".transition")
            ext = "mov" if layer == "overlay" else "mp4"
            out = out_dir / f"{name}.{ext}"
            if layer == "overlay":
                dur = (anim.get("timing") or {}).get("dur")
            elif layer == "transition":
                dur = anim.get("dur")
            else:
                dur = seg_dur
            cdir = comps / comp
            notes = []
            if not (cdir / "index.html").exists():
                notes.append("not built yet")
            if dur is None:
                notes.append("no measured timing — run retime.py")
            manifest = {}
            try:
                manifest = json.loads((cdir / "manifest.json").read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                pass
            is_kit = comp.startswith("kit/") or "kit" in manifest
            variables = {} if from_instance else dict(anim.get("vars") or {})
            if is_kit and not from_instance:
                if dur is not None:
                    variables["duration"] = round(dur, 3)
                variables["theme"] = theme
                if layer == "overlay" and anim.get("placement"):
                    variables["placement"] = anim["placement"]  # kit overlays declare a placement variable
                overrides = {m["recipe"]: m["params"] for m in motion_entries(anim) if m["params"]}
                if overrides:  # kit contract: the `motion` variable carries per-use recipe params
                    variables["motion"] = json.dumps(overrides, ensure_ascii=False)
            elif layer != "transition":  # a transition runs at its own length across the cut
                fixed = fixed_length(cdir)
                if fixed and dur and abs(fixed - dur) > 0.5:
                    notes.append(f"fixed length {fixed:g}s vs {dur:.1f}s — trim or hold in DaVinci")
            if "not built yet" in notes or dur is None:
                blocked += 1
                sh.append(f"# BLOCKED {name}: {'; '.join(notes)}")
            else:
                cmd = ["npx", "hyperframes", "render", "--fps", str(args.fps), "--resolution", args.resolution,
                       "--format", ext, "-o", str(out)]
                if variables:
                    cmd += ["--variables", json.dumps(variables, ensure_ascii=False)]
                sh.append(f"# {name} ← {comp}")
                sh.append(f"(cd {shlex.quote(str(cdir))} && {' '.join(shlex.quote(c) for c in cmd)})")
            sh.append("")
            rows.append(f"| {name} | {layer} | `{comp}` | {r['mode']}{' · kit' if is_kit else ''} | "
                        f"{'' if dur is None else f'{dur:.1f}s'} | {ext} | {'; '.join(notes)} |")

    (ep / "renders.sh").write_text("\n".join(sh), encoding="utf-8")
    os.chmod(ep / "renders.sh", 0o755)
    md = [f"# Renders — {sb.get('episode', ep.name)}", "",
          f"`renders.sh` renders into `renders/` at {args.fps} fps, {args.resolution}. Overlays are MOV "
          "(ProRes 4444, alpha); cutaways and transitions are MP4.", "",
          "| Output | Layer | Composition | Mode | Length | Format | Notes |", "|---|---|---|---|---|---|---|", *rows]
    (ep / "renders.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{len(rows)} renders · {len(rows) - blocked} ready · {blocked} blocked → {ep}/renders.sh, renders.md")


if __name__ == "__main__":
    main()
